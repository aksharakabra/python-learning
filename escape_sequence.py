# \n is an escape sequence for a new line
print("This is first\nthis is second")

# \t is an escape sequence for a tab
print("This is first\tthis is second")

# \\ is an escape sequence for a backslash
print("This is a backslash: \\")  

# \' is an escape sequence for a single quote
print('This is a single quote: \'')

# \" is an escape sequence for a double quote
print("This is a double quote: \"")

# \a is an escape sequence for an alert (bell)
print("This is an \aalert (bell):")

# \b is an escape sequence for a backspace
print("This is a \bbackspace")
